// Payout item model (SPEC §2.1). Payout currencies only: USD, EUR, GBP, SGD.
// VND is NOT a PayPal REST currency: a VND invoice is converted to USD
// before the PayPal call, never sent as VND.
export type PayoutCurrency = 'USD' | 'EUR' | 'GBP' | 'SGD';

export type PayoutItemStatus =
  | 'DRAFT'
  | 'AWAITING_APPROVAL'
  | 'APPROVED'
  | 'PENDING'
  | 'PROCESSING'
  | 'SUCCESS'
  | 'FAILED';

export interface PayoutItem {
  itemId: string; // Unique ID generated by the backend (UUID v4)
  recipientEmail: string; // Recipient PayPal email
  amount: number; // Monetary amount in `currency`
  currency: PayoutCurrency;
  recipientNote?: string; // Custom note to recipient
  senderItemId: string; // Unique transaction reference
  status: PayoutItemStatus;
  fxRiskScore: number; // AI-calculated FX risk (0.0 to 10.0)
  paypalTransactionId?: string; // Assigned upon webhook confirmation
  errorMessage?: string; // Guard-translated error if failed
}

export const PAYOUT_CURRENCIES: readonly PayoutCurrency[] = [
  'USD',
  'EUR',
  'GBP',
  'SGD',
];
